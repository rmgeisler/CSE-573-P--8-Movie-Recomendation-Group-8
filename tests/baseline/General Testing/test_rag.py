import os
print(os.getcwd())
import sys
import pyarrow
import pandas as pd

from openai import OpenAI
from getpass import getpass

import matplotlib.pyplot as plt

print("PyArrow version:", pyarrow.__version__)


# Add project root to Python path
sys.path.insert(0, "/home/sraoham1/CSE 573/CSE-573-P--8-Movie-Recomendation-Group-8")

from src.models.rag import MovieRAG
from src.kg.build_graph import KnowledgeGraph
from src.kg.retrieval import KGRetriever
from src.kg.sentence_transformer import SemanticNeighbors
from src.models.item_knn import ItemKNN

# ASU API client
client = OpenAI(
    api_key=getpass("Enter your ASU API key: "),
    base_url="https://openai.rc.asu.edu/v1",
    timeout=300.0,
    max_retries=1
)




# Load movie metadata
metadata = pd.read_parquet(
    "/home/sraoham1/CSE 573/CSE-573-P--8-Movie-Recomendation-Group-8/data/processed/metadata.parquet"
)

train = pd.read_parquet(
  "/home/sraoham1/CSE 573/CSE-573-P--8-Movie-Recomendation-Group-8/data/processed/train.parquet"
)

print("Metadata shape:", metadata.shape)
print("Columns:", metadata.columns.tolist())

# Initialize RAG
rag = MovieRAG(client=client)
rag.fit(metadata) # Build embeddings and FAISS index


# Initialize KG
kg = KnowledgeGraph.load(
   "/home/sraoham1/CSE 573/CSE-573-P--8-Movie-Recomendation-Group-8/data/kg/kg.pkl"
)
kg_retriever = KGRetriever(kg)

# Load semantic embeddings generated by KG
semantic_neighbors = SemanticNeighbors.load(
    "/home/sraoham1/CSE 573/CSE-573-P--8-Movie-Recomendation-Group-8/data/kg/plot_embeddings.npz"
)
# Configure KG and semantic evidence
rag.configure_evidence(
    train=train,
    kg_retriever=kg_retriever,
    semantic_neighbors=semantic_neighbors
)

# Initialize and train ItemKNN
knn_model = ItemKNN()
knn_model.fit(train)

# Test one user from the training data
user_ids = train["user_idx"].unique()

user_choice = int(input("Select user position (0-9): "))

if 0 <= user_choice < min(10, len(user_ids)):
    user_idx = int(user_ids[user_choice])
    print("Selected User ID:", user_idx)
else:
    raise ValueError("Invalid selection. Enter a number between 0 and 9.")

# Get movies already seen by this user
seen = set(
    train.loc[train["user_idx"] == user_idx, "movie_idx"]
)

# Generate KNN candidates
knn_candidates = knn_model.recommend(
    user_idx,
    seen,
    k=100  #100
)

print("KNN candidates:", len(knn_candidates))

recommendations = rag.recommend_for_user(
    user_idx=user_idx,
    top_k=10,
    candidate_k=100,
    knn_candidates=knn_candidates
)


print("Recommendation process completed!")
print("Number of recommendations:", len(recommendations))

# print("\nTop 10 Movie Recommendations:")
# print(recommendations[["movie_idx", "title", "candidate_source"]])

# Create recommendation plot data
plot_data = recommendations[["movie_idx", "title", "candidate_source"]].copy()
plot_data["rank"] = range(1, len(plot_data) + 1)

# Reverse order so Rank 1 appears at the top
plot_data = plot_data.iloc[::-1]

plt.figure(figsize=(14, 8))

bars = plt.barh(
    plot_data["title"],
    11 - plot_data["rank"]
)

plt.xlabel("Relative Ranking (Higher = Better)")
plt.ylabel("Movie Title")
plt.title("Top 10 Movie Recommendations")

plt.xticks(range(1, 11))
plt.xlim(0, 13)
plt.grid(axis="x", linestyle="--", alpha=0.4)

# Display movie index and candidate source
for bar, movie_idx, source in zip(
    bars,
    plot_data["movie_idx"],
    plot_data["candidate_source"]
):
    plt.text(
        bar.get_width() + 0.15,
        bar.get_y() + bar.get_height() / 2,
        f"ID: {movie_idx} | Source: {source}",
        va="center",
        fontsize=9
    )

plt.tight_layout()
plt.show()

print("\nAvailable columns:")
print(recommendations.columns.tolist())